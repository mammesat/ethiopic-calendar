<?php

/**
 * Generates tests/fixtures/dates.json: every day of Ethiopian years 1990–2060.
 *
 * The fixtures are built WITHOUT the package's Converter, so testing the
 * converter against them is not circular:
 *
 *  - Gregorian dates come from PHP's DateTimeImmutable, stepping one day at a time.
 *  - Ethiopian dates come from stepping one day at a time through the plain
 *    month rules (12 × 30 days, Pagume 5 or 6 when year mod 4 = 3).
 *  - JDN comes from the Unix timestamp (JDN 2440588 = 1970-01-01).
 *  - The walk starts from one independently known anchor:
 *    1 Meskerem 1990 = 11 September 1997.
 *
 * Each row: [gregorian Y-m-d, ethiopian Y-m-d, jdn, iso weekday 1–7].
 *
 * Usage: php bin/generate-fixtures.php
 */

declare(strict_types=1);

const FIRST_YEAR = 1990;
const LAST_YEAR = 2060;

$gregorian = new DateTimeImmutable('1997-09-11', new DateTimeZone('UTC'));
[$ey, $em, $ed] = [FIRST_YEAR, 1, 1];

$rows = [];

while ($ey <= LAST_YEAR) {
    $jdn = intdiv($gregorian->getTimestamp(), 86400) + 2440588;

    $rows[] = [
        $gregorian->format('Y-m-d'),
        sprintf('%04d-%02d-%02d', $ey, $em, $ed),
        $jdn,
        (int) $gregorian->format('N'),
    ];

    $gregorian = $gregorian->modify('+1 day');

    $monthLength = $em <= 12 ? 30 : ($ey % 4 === 3 ? 6 : 5);

    if (++$ed > $monthLength) {
        $ed = 1;

        if (++$em > 13) {
            $em = 1;
            $ey++;
        }
    }
}

$json = "{\n"
    .'  "description": "Every day of Ethiopian years '.FIRST_YEAR.'-'.LAST_YEAR.'. Generated by bin/generate-fixtures.php without the package converter.",'."\n"
    .'  "columns": ["gregorian", "ethiopian", "jdn", "isoWeekday"],'."\n"
    ."  \"rows\": [\n"
    .implode(",\n", array_map(static fn (array $r): string => '    '.json_encode($r), $rows))
    ."\n  ]\n}\n";

$target = __DIR__.'/../tests/fixtures/dates.json';

if (! is_dir(dirname($target))) {
    mkdir(dirname($target), 0777, true);
}

file_put_contents($target, $json);

fwrite(STDOUT, sprintf("Wrote %d rows to tests/fixtures/dates.json (%s to %s)\n", count($rows), $rows[0][0], end($rows)[0]));
